def test_the_document_covers_the_schema_and_is_deterministic() -> None:
    document = dictionary.build()
    schema = yaml.safe_load((REPOSITORY / "config/dataset.yaml").read_text())
    assert document["format"] == dictionary.FORMAT
    assert list(document["tables"]) == list(schema)
    assert [t["name"] for t in document["tools"]][-1] == "describe"
    assert document["tools"][0] == {**document["tools"][0], "pack": "core"}
    assert json.loads(dictionary.render_json(document)) == document
    assert dictionary.render_json(dictionary.build()) == dictionary.render_json(
        document
    )


def test_status_values_and_enumerations_are_in_the_document() -> None:
    document = dictionary.build()
    assert [i["value"] for i in document["results"]["status"]][:3] == [
        "matched",
        "ambiguous",
        "not_found",
    ]
    columns = {c["name"]: c for c in document["tables"]["cells"]["columns"]}
    assert "rural_nearest_distant" in [
        v["value"] for v in columns["city_method"]["values"]
    ]
    assert document["tables"]["places"]["used_by"] == list(document["packs"])


def test_committed_outputs_are_current() -> None:
    assert dictionary.stale() == []
    assert pipeline_main(["dictionary", "--check"]) == 0


def sources() -> set[str]:
    schema = yaml.safe_load((REPOSITORY / "config/dataset.yaml").read_text())
    return {
        path
        for table in schema.values()
        for column in table["columns"]
        for path in column.get("values_from", [])
    }


def mirror(destination: Path) -> Path:
    """A repository holding only the files the generator reads, then its outputs."""
    for relative in (*INPUTS, *sorted(sources())):
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(REPOSITORY / relative, target)
    dictionary.write(destination)
    return destination


def test_check_names_every_file_a_schema_edit_makes_stale(tmp_path: Path) -> None:
    repository = mirror(tmp_path)
    assert dictionary.stale(repository) == []
    schema = repository / "config/dataset.yaml"
    schema.write_text(
        schema.read_text().replace("Canonical city/town anchor ID", "Edited")
    )
    assert dictionary.stale(repository) == [
        "docs/dataset/DATA_DICTIONARY.md",
        "docs/dataset/data_dictionary.json",
        "clients/python/thereabouts/dictionary/DATA_DICTIONARY.md",
        "clients/python/thereabouts/dictionary/data_dictionary.json",
        "skills/thereabouts/references/tables.md",
    ]


def test_check_notices_a_change_in_the_rust_vocabulary(tmp_path: Path) -> None:
    repository = mirror(tmp_path)
    source = repository / "core/thereabouts-core/src/result.rs"
    source.write_text(
        source.read_text().replace("Several ranked places", "Many places")
    )
    assert "skills/thereabouts/references/mcp-tools.md" in dictionary.stale(repository)


def test_check_reports_a_missing_file_and_main_fails(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    repository = mirror(tmp_path)
    (repository / "skills/thereabouts/references/tables.md").unlink()
    assert dictionary.main(["--check"], repository) == 1
    assert "stale: skills/thereabouts/references/tables.md" in capsys.readouterr().out
    assert dictionary.main([], repository) == 0
    assert dictionary.main(["--check"], repository) == 0


def test_a_new_table_needs_only_schema_metadata(tmp_path: Path) -> None:
    repository = mirror(tmp_path)
    schema = repository / "config/dataset.yaml"
    value = yaml.safe_load(schema.read_text())
    value["names"] = {
        "description": "Alternate names.",
        "grain": "One row per name.",
        "primary_key": [],
        "relationships": [
            {
                "columns": ["city_id"],
                "references": {"table": "places", "columns": ["place_id"]},
                "meaning": "The named city",
            }
        ],
        "columns": [
            {
                "name": "city_id",
                "type": "string",
                "nullable": False,
                "meaning": "City",
                "units": "none",
            }
        ],
    }
    schema.write_text(yaml.safe_dump(value, sort_keys=False))
    document = dictionary.build(repository)
    assert document["tables"]["names"]["relationships"][0]["references"]["table"] == (
        "places"
    )
    assert (
        "### `names`"
        in dictionary.outputs(repository)["skills/thereabouts/references/tables.md"]
    )


def test_install_drops_both_documents_and_is_idempotent(tmp_path: Path) -> None:
    first = dictionary.install(tmp_path / "release")
    assert [p.name for p in first] == ["DATA_DICTIONARY.md", "data_dictionary.json"]
    before = [p.read_bytes() for p in first]
    assert [p.read_bytes() for p in dictionary.install(tmp_path / "release")] == before
    assert json.loads(first[1].read_text())["format"] == dictionary.FORMAT
    assert dictionary.documents().keys() == {p.name for p in first}


