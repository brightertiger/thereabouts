"""The MCP server serves the data dictionary and describes the dataset tables."""

import asyncio
import json
from collections.abc import Awaitable, Callable
from importlib import resources
from pathlib import Path
from typing import Any, cast

from mcp import Client
from mcp.types import TextResourceContents

from thereabouts import Geocoder, _core
from thereabouts.mcp_service import dictionary
from thereabouts.mcp_service.server import create_server

FIXTURES = Path(__file__).parents[2] / "fixtures"
CORE = FIXTURES / "packs/core-sample"
DATASET = FIXTURES / "datasets/core-synthetic/golden"
URIS = ("thereabouts://dictionary", "thereabouts://dictionary/markdown")


def serve(
    geo: Geocoder, step: Callable[[Client], Awaitable[Any]]
) -> Any:  # one stdio-free client session against an in-process server
    async def session() -> Any:
        async with Client(create_server(geo)) as client:
            return await step(client)

    return asyncio.run(session())


def read(geo: Geocoder, uri: str) -> TextResourceContents:
    async def step(client: Client) -> TextResourceContents:
        contents = (await client.read_resource(uri)).contents
        assert len(contents) == 1 and isinstance(contents[0], TextResourceContents)
        return contents[0]

    result: TextResourceContents = serve(geo, step)
    return result


def describe(geo: Geocoder, **arguments: Any) -> Any:
    async def step(client: Client) -> Any:
        return await client.call_tool("describe", arguments)

    return serve(geo, step)


def test_both_resources_are_listed_with_their_types() -> None:
    async def step(client: Client) -> dict[str, str | None]:
        return {r.uri: r.mime_type for r in (await client.list_resources()).resources}

    with Geocoder(CORE) as geo:
        assert serve(geo, step) == {
            URIS[0]: "application/json",
            URIS[1]: "text/markdown",
        }


def test_a_core_pack_without_a_dictionary_falls_back_to_the_packaged_copy() -> None:
    with Geocoder(CORE) as geo:
        content = read(geo, URIS[0])
        document = json.loads(content.text)
        assert content.mime_type == "application/json"
        assert document["format"] == "thereabouts-data-dictionary-1"
        assert set(document["tables"]) >= {"places", "cells", "canonical_cities"}
        text = read(geo, URIS[1]).text
        assert text.startswith("<!-- Generated by")
        assert "# Thereabouts data dictionary" in text


def test_the_packaged_copy_is_importable_and_equals_the_documented_one() -> None:
    root = resources.files("thereabouts") / "dictionary"
    assert (
        dictionary.packaged().json_text == (root / "data_dictionary.json").read_text()
    )
    docs = Path(__file__).parents[3] / "docs/dataset"
    assert (
        dictionary.packaged().json_text == (docs / "data_dictionary.json").read_text()
    )
    assert (
        dictionary.packaged().markdown_text == (docs / "DATA_DICTIONARY.md").read_text()
    )


def pack_with_dictionary(destination: Path) -> Path:
    packaged = dictionary.packaged()
    document = {**packaged.document, "about": "Dictionary shipped inside the pack"}
    original = json.loads((FIXTURES / "packs/core-synthetic/manifest.json").read_text())
    options = original["inputs"]["options"] | {
        "notices": {
            **original["inputs"]["options"]["notices"],
            dictionary.JSON_NOTICE: json.dumps(document),
            dictionary.MARKDOWN_NOTICE: "# Pack dictionary\n",
        },
        "staging_directory": str(destination / "scratch"),
        "sqlite_directory": str(destination / "sqlite"),
    }
    pack = destination / "pack"
    _core.write_pack(str(DATASET), "core", str(pack), options)
    return pack


def test_the_installed_core_packs_dictionary_is_preferred(tmp_path: Path) -> None:
    pack = pack_with_dictionary(tmp_path)
    assert dictionary.from_pack(pack) is not None
    with Geocoder(pack) as geo:
        document = json.loads(read(geo, URIS[0]).text)
        assert document["about"] == "Dictionary shipped inside the pack"
        assert read(geo, URIS[1]).text == "# Pack dictionary\n"
        assert describe(geo).structured_content["about"] == document["about"]


def test_a_pack_with_only_one_of_the_pair_is_ignored(tmp_path: Path) -> None:
    pack = pack_with_dictionary(tmp_path)
    for path in pack.glob("notice-*.txt"):
        if path.read_text().startswith(dictionary.MARKDOWN_NOTICE):
            text = path.read_text().replace(dictionary.MARKDOWN_NOTICE, "OTHER.md", 1)
            path.write_text(text)
    assert dictionary.from_pack(pack) is None


def test_describe_lists_every_table_then_one_table_in_full() -> None:
    with Geocoder(CORE) as geo:
        listed = describe(geo)
        assert not listed.is_error
        names = [t["name"] for t in listed.structured_content["tables"]]
        assert "places" in names and "cells" in names
        one = describe(geo, table="places").structured_content
        assert one["name"] == "places" and one["primary_key"] == ["place_id"]
        assert {c["name"] for c in one["columns"]} >= {"place_id", "role", "population"}
        assert one["relationships"][0]["references"]["table"] == "places"
        role = next(c for c in one["columns"] if c["name"] == "role")
        assert "settlement" in [v["value"] for v in role["values"]]


def test_describe_rejects_an_unknown_table_and_names_the_valid_ones() -> None:
    with Geocoder(CORE) as geo:
        failed = describe(geo, table="nope")
        assert failed.is_error
        assert "Unknown table 'nope'" in str(failed.content)
        assert "places" in str(failed.content)


def test_describe_needs_no_installed_core_pack() -> None:
    with Geocoder(FIXTURES / "packs/postal-sample") as geo:
        assert not describe(geo, table="postal_codes").is_error


def test_tool_descriptions_state_status_semantics_and_evidence() -> None:
    async def step(client: Client) -> dict[str, str]:
        return {t.name: t.description or "" for t in (await client.list_tools()).tools}

    with Geocoder(CORE) as geo:
        tools = serve(geo, step)
    assert "not_found" in tools["reverse"] and "nearest_distant" in tools["reverse"]
    assert "evidence" in tools["reverse"] and "no_land" in tools["reverse"]
    assert (
        "ambiguous" in tools["geocode"]
        and "unsupported_granularity" in tools["geocode"]
    )
    assert "ambiguous" in tools["postal"] and "invalid_input" in tools["postal"]
    assert "ambiguous" in tools["plate"]
    assert all(description for description in tools.values())


def test_creating_a_server_never_touches_the_geocoder_or_the_disk() -> None:
    async def names() -> set[str]:
        server = create_server(cast(Geocoder, None))
        return {tool.name for tool in await server.list_tools()}

    assert "describe" in asyncio.run(names())
