"""Append reproducible coverage and benchmark measurements to the plate guide."""

import argparse
from collections import Counter
from pathlib import Path

from build_data.acquire.artifacts import read_json
from build_data.acquire.io import sha256_file, write_json

from .build import verify
from .resolver import Resolver

MARKER = "<!-- plate-country-measurements:start -->"


def percent(value: float | None) -> str:
    return "—" if value is None else f"{value:.1%}"


def cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ")


def measurements(data: Path) -> str:
    verify(data)
    root = data / "normalized" / "plates_country"
    manifest = read_json(root / "manifest.json")
    resolver = Resolver.load(root)
    report = read_json(root / "evaluation.json")
    if report["manifest_sha256"] != sha256_file(root / "manifest.json"):
        raise ValueError("Evaluation belongs to another release; run evaluate")
    coverage = read_json(root / manifest["coverage"])["countries"]
    metrics = report["metrics"]
    total = metrics["all"]
    holdout = metrics["holdout"]
    lines = [
        MARKER,
        "## Country-inference measurements and format inventory",
        "",
        "Generated by `python -m build_data.plate_country.report --data-dir data`.",
        f"Before: **151/250** countries with 159 format rows. After: "
        f"**{manifest['counts']['countries']}/250** with "
        f"**{manifest['counts']['formats']}** format evidence rows. "
        "These counts mean at least one modeled series, not complete coverage.",
        "",
        f"The benchmark contains **{total['n']}** distinct documented plates from "
        f"**{total['countries']}** countries: {metrics['development']['n']} "
        f"development examples and **{holdout['n']} held-out examples**. "
        "It contains 72 caption/filename transcriptions, 51 visually transcribed "
        "photographed plates and 4 published specimens. The latter are not "
        "claimed to be issued serials or government-certified specimens.",
        "",
        "| Region | All n | All top-1 | All top-3 | "
        "Holdout n | Holdout top-1 | Holdout top-3 |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for region in ("Overall", "Africa", "Americas", "Asia", "Europe", "Oceania"):
        suffix = "" if region == "Overall" else "/" + region
        all_rows = metrics["all" + suffix]
        held = metrics.get("holdout" + suffix, dict(n=0, top1=None, top3=None))
        lines.append(
            f"| {region} | {all_rows['n']} | {percent(all_rows['top1'])} | "
            f"{percent(all_rows['top3'])} | {held['n']} | "
            f"{percent(held['top1'])} | {percent(held['top3'])} |"
        )
    lines += [
        "",
        f"Truth appears anywhere in the candidate list for "
        f"{percent(total['candidate_recall'])} overall and "
        f"{percent(holdout['candidate_recall'])} on holdout. "
        "No unhinted result is certified as certain. The absence of an Americas "
        "holdout example is a sampling gap, not a zero-accuracy measurement.",
        "",
        "| Supplied-country level | All examples | Holdout examples |",
        "| --- | ---: | ---: |",
    ]
    for level in ("place", "state", "country"):
        lines.append(
            f"| {level} | {total['hint_levels'].get(level, 0)} | "
            f"{holdout['hint_levels'].get(level, 0)} |"
        )
    lines += [
        "",
        "Every supplied-country example retains that country. Geographic levels "
        "measure what evidence was available, **not independently checked place "
        "accuracy**. Country-only reasons in this sample:",
        "",
    ]
    lines += [
        f"- `{reason}`: {count}."
        for reason, count in sorted(total["hint_reasons"].items())
        if reason
        not in ("known_registration_code", "known_state_code_no_finer_verified_unit")
    ]
    lines += [
        "",
        "The full scored rows, candidate rankings, image/caption provenance, "
        "split assignments and denominators are in "
        "`data/normalized/plates_country/evaluation.json`.",
        "",
        "### Per-country format coverage",
        "",
        "C/H are counts of current/historic **evidence rows**, including duplicate "
        "source assertions and non-ordinary series. All coverage remains partial. "
        "The bundle records exact regexes, separators, marks, code groups and "
        "evidence. No-format territories are not asserted to be non-issuers.",
        "",
        "| ISO | Country/territory | C/H | Scripts (digits included) | Sources |",
        "| --- | --- | ---: | --- | --- |",
    ]
    for country in sorted(coverage, key=lambda r: r["country_code"]):
        rules = [
            r for r in resolver.formats if r["country_code"] == country["country_code"]
        ]
        counts = Counter(r["series_status"] for r in rules)
        scripts = sorted({script for r in rules for script in r["scripts"]})
        urls = sorted({r["provenance"]["url"] for r in rules})
        links = ", ".join(f"[{i}]({url})" for i, url in enumerate(urls, 1))
        lines.append(
            f"| {country['country_code']} | {cell(country['name'])} | "
            f"{counts['current']}/{counts['historic']} | "
            f"{cell(', '.join(scripts)) or 'Gap'} | {links or 'Unsourced grammar'} |"
        )
    lines += ["", "### Explicit missing formats and incomplete issuing series", ""]
    for country in sorted(coverage, key=lambda r: r["country_code"]):
        if country["status"] == "gap" or country["gap"] != (
            "Special, vanity and some historical series are not exhaustively modeled."
        ):
            lines.append(
                f"- **{country['country_code']} {country['name']}**: {country['gap']}"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument("--output", type=Path, default=Path("docs/PLATES.md"))
    args = parser.parse_args()
    original = args.output.read_text(encoding="utf-8")
    prefix = original.split(MARKER)[0].rstrip()
    args.output.write_text(
        prefix + "\n\n" + measurements(args.data_dir), encoding="utf-8"
    )
    write_json(
        args.output.with_name("plate-country-evaluation.json"),
        read_json(args.data_dir / "normalized" / "plates_country" / "evaluation.json"),
    )


if __name__ == "__main__":
    main()
